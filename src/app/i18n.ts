const copies: Record<Locale, Copy> = { en, fr }
type Translate = (key: keyof Copy, values?: Record<string, string | number>) => string
const translators: Record<Locale, Translate> = {
  en: (key, values = {}) => interpolate(copies.en[key], values),
  fr: (key, values = {}) => interpolate(copies.fr[key], values),
}

export function detectLocale(language = navigator.language): Locale {
  return /^fr(?:-|$)/i.test(language) ? 'fr' : 'en'
}

function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
}

export function useI18n() {
  const locale = detectLocale()
  return { locale, t: translators[locale] }
}

export function localizedKnownMessage(message: string, locale: Locale): string | undefined {
  if (locale === 'en') return message
  const t = (key: keyof Copy, values: Record<string, string | number> = {}) => interpolate(fr[key], values)
  const exact: Partial<Record<string, keyof Copy>> = {
    'Local storage is unavailable.': 'localStorageUnavailable',
    'Changes were not applied.': 'changesNotApplied',
    'This score no longer exists.': 'scoreMissing',
    'Save failed. Try again.': 'saveFailed',
    'Saved.': 'saved',
    'Could not save the score.': 'scoreSaveFailed',
    'The performance could not be generated.': 'performanceCreateFailed',
    'The drums-intro spacing preference was relaxed because no alternative was available.': 'drumsRelaxed',
    'Choose a Piece Selector .json settings file.': 'chooseSettingsFile',
    'The settings file could not be opened.': 'settingsFileOpenFailed',
    'No settings were changed.': 'noSettingsChanged',
    'Settings file is not valid JSON.': 'settingsInvalidJson',
    'This is not a Piece Selector settings file.': 'settingsWrongFile',
    'This settings file version is not supported.': 'settingsUnsupported',
    'This Piece Selector settings file is malformed.': 'settingsMalformed',
    'Set-list file is not valid JSON.': 'setListInvalidJson',
    'This is not a Piece Selector set-list file.': 'setListWrongFile',
    'This set-list file version is not supported.': 'setListUnsupported',
    'This Piece Selector set-list file is malformed.': 'setListMalformed',
    'Every imported set must contain the same number of pieces.': 'setListSameSize',
    'Every imported set must start with an eligible starter.': 'setListInvalidStarter',
    'A piece appears more than once in the imported set list.': 'setListRepeatedPiece',
    'Pieces that go high must remain near the start of their set.': 'setListInvalidHighOrder',
  }
  const key = exact[message]
  if (key) return t(key)

  const dynamic: Array<[RegExp, keyof Copy, string[]]> = [
    [/^Sets must be a whole number from (\d+) to (\d+)\.$/, 'generatorSetsRange', ['min', 'max']],
    [/^Scores per set must be a whole number from (\d+) to (\d+)\.$/, 'generatorPiecesRange', ['min', 'max']],
    [/^This performance needs (\d+) eligible scores, but (\d+) are available\./, 'generatorEligible', ['required', 'available']],
    [/^This performance needs (\d+) distinct starters, but (\d+) are available\./, 'generatorStarters', ['required', 'available']],
    [/^Piece (\d+) has malformed settings\.$/, 'settingsPieceMalformed', ['number']],
    [/^Piece (\d+) has an invalid score number\.$/, 'settingsInvalidNumber', ['number']],
    [/^Score number (\d+) appears more than once in the settings file\.$/, 'settingsDuplicateNumber', ['number']],
    [/^Score number (\d+) has no name\.$/, 'settingsMissingName', ['number']],
    [/^Score number (\d+) has malformed settings\.$/, 'settingsScoreMalformed', ['number']],
  ]
  for (const [pattern, messageKey, names] of dynamic) {
    const match = message.match(pattern)
    if (!match) continue
    return t(messageKey, Object.fromEntries(names.map((name, index) => [name, match[index + 1] ?? ''])))
  }
  return undefined
}

export function localizedError(error: unknown, locale: Locale, fallback: string): string {
  return error instanceof Error ? localizedKnownMessage(error.message, locale) ?? fallback : fallback
}
